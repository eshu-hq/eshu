package main

import (
	"bytes"
	"fmt"
	"sort"
	"strings"

	"github.com/eshu-hq/eshu/go/internal/facts/contract"
)

// renderCatalogPage renders one family's human catalog page: current
// producers and emitted kinds, canonical fact owner, per-kind reducer
// consumers or no-reducer disposition, read surfaces, and schema
// references (with missing registrations disclosed).
func renderCatalogPage(fam discoveredFamily, entryByKind map[string]registryEntry, bindingsByKind, producersByKind map[string][]string) []byte {
	f := fam.family
	var buf bytes.Buffer
	buf.WriteString("<!-- Generated by go/cmd/fact-kind-registry; DO NOT EDIT. -->\n\n")
	fmt.Fprintf(&buf, "# Fact family: %s\n\n", f.ID)
	fmt.Fprintf(&buf, "- Canonical fact owner: `%s`\n", f.OwnerRepository)
	fmt.Fprintf(&buf, "- Fact definitions: `%s` (declared at %s)\n", f.FactDir, fam.pos)
	fmt.Fprintf(&buf, "- Reducer domain: `%s`\n", f.ReducerDomain)
	fmt.Fprintf(&buf, "- Read surface: `%s`\n\n", f.ReadSurface)
	buf.WriteString("## Producers\n\n")
	buf.WriteString("| Producer | Repository | Path | Planned repository | Authority | Emitted kinds |\n")
	buf.WriteString("| --- | --- | --- | --- | --- | --- |\n")
	producers := append([]contract.Producer(nil), f.Producers...)
	sort.Slice(producers, func(i, j int) bool { return producers[i].ID < producers[j].ID })
	for _, p := range producers {
		kinds := append([]string(nil), p.Kinds...)
		sort.Strings(kinds)
		fmt.Fprintf(&buf, "| `%s` | `%s` | `%s` | `%s` | `%s` | `%s` |\n", p.ID, p.Repository, p.Path, p.PlannedRepository, p.AuthorityMode, strings.Join(kinds, ", "))
	}
	buf.WriteString("\n## Kinds\n\n")
	buf.WriteString("| Kind | Producers | Reducer consumers | Read surface | Payload schema |\n")
	buf.WriteString("| --- | --- | --- | --- | --- |\n")
	kindNames := make([]string, 0, len(f.Kinds))
	declaredByKind := map[string]int{}
	for i, kind := range f.Kinds {
		kindNames = append(kindNames, kind.Kind)
		declaredByKind[kind.Kind] = i
	}
	sort.Strings(kindNames)
	for _, name := range kindNames {
		declared := f.Kinds[declaredByKind[name]]
		entry := entryByKind[name]
		consumers := "none (" + string(declared.Disposition) + ")"
		if ids := bindingsByKind[name]; len(ids) > 0 {
			sorted := append([]string(nil), ids...)
			sort.Strings(sorted)
			consumers = strings.Join(sorted, ", ")
		}
		schema := entry.PayloadSchema
		if schema == "" {
			schema = "none (disclosed: no schema registration)"
		}
		fmt.Fprintf(&buf, "| `%s` | `%s` | `%s` | `%s` | `%s` |\n", name,
			strings.Join(sortedUnique(producersByKind[name]), ", "), consumers, entry.ReadSurface, schema)
	}
	return buf.Bytes()
}
