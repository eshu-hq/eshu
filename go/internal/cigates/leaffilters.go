package cigates

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Leaf filter file locations, relative to the repository root. The three
// code-gated workflows (test.yml, security-scan.yml, mcp-schema-drift.yml)
// consume these files through dorny/paths-filter `filters:` references
// instead of carrying their own inline copies (#10980; the #5818 drift
// class). The static-contract matrix keeps its own filters file, which
// mirrors registry triggers rather than the docs set.
const (
	leafCodeFilterFile     = ".github/leaf-code-filter.yml"
	leafLockstepFilterFile = ".github/leaf-lockstep-filter.yml"
	docsSetPatternsFile    = "specs/ci-docs-set-patterns.txt"
	lockstepManifestFile   = "specs/ci-docs-lockstep-paths.txt"
)

// leafFilterHeader names the specs source a generated leaf filter derives
// from. The header is part of the freshness contract: the drift check
// compares full file bytes, so any hand edit to generated output fails
// loudly instead of drifting silently.
func leafFilterHeader(source string) string {
	return "# DO NOT EDIT — generated by `go run ./cmd/ci-gates generate-leaf-filters`\n" +
		"# from " + source + ". test.yml, security-scan.yml, and\n" +
		"# mcp-schema-drift.yml consume this file instead of carrying their own\n" +
		"# copies (#10980; the #5818 drift class). Edit the specs, then regenerate.\n"
}

// DocsSetPatterns reads the canonical docs-set pattern file: the changed
// paths that cannot affect compiled, tested, or scanned behavior, one
// MatchGlob pattern per line. `#` comments and blank lines are skipped. An
// empty result is an error rather than an empty filter: the generator must
// never emit a bare `code: ['**']`, which would select every PR including
// docs-only ones.
func DocsSetPatterns(root string) ([]string, error) {
	raw, err := os.ReadFile(filepath.Join(root, docsSetPatternsFile)) // #nosec G304 -- caller supplies a repository checkout root.
	if err != nil {
		return nil, fmt.Errorf("read docs-set patterns: %w", err)
	}
	var patterns []string
	for _, line := range strings.Split(string(raw), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if strings.HasPrefix(line, "!") {
			return nil, fmt.Errorf("docs-set pattern %q is negated: the spec holds positive docs-set globs, negation is the generator's job", line)
		}
		patterns = append(patterns, line)
	}
	if len(patterns) == 0 {
		return nil, fmt.Errorf("docs-set patterns file holds no patterns")
	}
	return patterns, nil
}

// GenerateLeafCodeFilter renders the dorny `code` filter from docs-set
// patterns: a `**` positive narrowed by one negation per pattern. A
// `**/*.md` entry expands to both `*.md` and `**/*.md` because
// dorny/picomatch treats a slash-free pattern as root-only while MatchGlob
// `**` crosses segments; every other pattern negates verbatim, so the
// emitted block stays identical to the inline blocks the workflows carry
// today. The output must run under `predicate-quantifier: every`: under the
// default `some`, `**` matches first and the negations are inert (#5896).
func GenerateLeafCodeFilter(patterns []string) (string, error) {
	if len(patterns) == 0 {
		return "", fmt.Errorf("no docs-set patterns: refusing to emit an unnegated code filter")
	}
	var b strings.Builder
	b.WriteString(leafFilterHeader(docsSetPatternsFile))
	b.WriteString("code:\n  - '**'\n")
	for _, pattern := range patterns {
		if strings.HasPrefix(pattern, "!") {
			return "", fmt.Errorf("docs-set pattern %q is negated: the spec holds positive docs-set globs", pattern)
		}
		if pattern == "**/*.md" {
			b.WriteString("  - '!*.md'\n  - '!**/*.md'\n")
			continue
		}
		fmt.Fprintf(&b, "  - '!%s'\n", pattern)
	}
	return b.String(), nil
}

// GenerateLeafLockstepFilter renders the dorny `lockstep` filter from the
// canonical lockstep manifest, in manifest order. The output must run under
// the default `some` quantifier: a PR touching ANY listed test input must
// run the code-gated lanes, while `every` would require one file to match
// all entries at once and select nothing.
func GenerateLeafLockstepFilter(lockstep []string) (string, error) {
	if len(lockstep) == 0 {
		return "", fmt.Errorf("no lockstep entries: refusing to emit an empty lockstep filter")
	}
	var b strings.Builder
	b.WriteString(leafFilterHeader(lockstepManifestFile))
	b.WriteString("lockstep:\n")
	for _, entry := range lockstep {
		if strings.Contains(entry, "'") || strings.Contains(entry, "\n") {
			return "", fmt.Errorf("lockstep entry %q is not single-quote safe", entry)
		}
		fmt.Fprintf(&b, "  - '%s'\n", entry)
	}
	return b.String(), nil
}

// generateLeafFilters renders both leaf filters from the committed specs.
// It is the single derivation the drift check and the generate-leaf-filters
// command share, so the two cannot disagree about what "fresh" means.
func generateLeafFilters(root string) (code, lock string, err error) {
	patterns, err := DocsSetPatterns(root)
	if err != nil {
		return "", "", err
	}
	lockstep, err := LockstepManifestPaths(root)
	if err != nil {
		return "", "", err
	}
	code, err = GenerateLeafCodeFilter(patterns)
	if err != nil {
		return "", "", err
	}
	lock, err = GenerateLeafLockstepFilter(lockstep)
	if err != nil {
		return "", "", err
	}
	return code, lock, nil
}

// WriteLeafFilters regenerates both leaf filters from the committed specs
// and writes them to their canonical paths under root, returning the files
// written. It is the `--repo-root` half of the generate-leaf-filters
// command; the drift check proves the committed files match.
func WriteLeafFilters(root string) ([]string, error) {
	code, lock, err := generateLeafFilters(root)
	if err != nil {
		return nil, err
	}
	files := map[string]string{leafCodeFilterFile: code, leafLockstepFilterFile: lock}
	wrote := make([]string, 0, len(files))
	for _, file := range []string{leafCodeFilterFile, leafLockstepFilterFile} {
		dest := filepath.Join(root, file)
		if err := os.MkdirAll(filepath.Dir(dest), 0o700); err != nil {
			return wrote, fmt.Errorf("create generated leaf filter dir for %s: %w", file, err)
		}
		if err := os.WriteFile(dest, []byte(files[file]), 0o600); err != nil {
			return wrote, fmt.Errorf("write generated leaf filter %s: %w", file, err)
		}
		wrote = append(wrote, file)
	}
	return wrote, nil
}

// checkLeafFilterFreshness regenerates both leaf filters from the committed
// specs and reports any byte difference against the committed files. It runs
// inside DriftCheck, so a hand edit to generated output — or a specs edit
// without regenerating — fails the registry gate instead of forking CI and
// local selection.
func checkLeafFilterFreshness(root string) []error {
	// Synthetic drift fixtures build minimal repos without any leaf filter
	// artifacts; all four absent means there is nothing to prove fresh, and
	// the check skips. Any subset present is itself checkable: a missing
	// piece then fails loudly below instead of passing silently.
	present := false
	for _, file := range []string{docsSetPatternsFile, lockstepManifestFile, leafCodeFilterFile, leafLockstepFilterFile} {
		if _, err := os.Stat(filepath.Join(root, file)); err == nil {
			present = true
			break
		}
	}
	if !present {
		return nil
	}
	code, lock, err := generateLeafFilters(root)
	if err != nil {
		return []error{err}
	}
	var errs []error
	for file, want := range map[string]string{leafCodeFilterFile: code, leafLockstepFilterFile: lock} {
		got, err := os.ReadFile(filepath.Join(root, file)) // #nosec G304 -- paths are package constants under the checked-out root.
		if err != nil {
			errs = append(errs, fmt.Errorf("drift: read generated leaf filter %s: %w", file, err))
			continue
		}
		if string(got) != want {
			errs = append(errs, fmt.Errorf("drift: generated leaf filter %s differs from specs; regenerate with `go run ./cmd/ci-gates generate-leaf-filters --repo-root <root>`", file))
		}
	}
	return errs
}
