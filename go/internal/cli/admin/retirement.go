package admin

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"strings"
)

// RetireInput carries the selectors and the operator's justification for
// Retire. Reason is mandatory; IdempotencyKey is generated when blank.
type RetireInput struct {
	// Repositories holds the repository selectors (repository ID, scope
	// ID, name, slug, or path); repeatable, 1 to 25.
	Repositories []string
	// Reason must be non-blank: Retire rejects the request before any HTTP
	// call otherwise.
	Reason string
	// IdempotencyKey is generated by NewRetireIdempotencyKey when blank.
	IdempotencyKey string
}

// Retire triggers the operator-driven repository retirement (mark, fence,
// then purge) and returns the decoded response body. Callers that print the
// key before the call (the cobra wrapper does) pass an explicit key so the
// operator always knows it, even when the call fails after the fence commits. It refuses a blank
// Reason and generates an idempotency key when the caller supplies none, so
// a retried invocation resumes the open retirement instead of opening a
// second one.
//
// The blank-Reason error names the `--reason` CLI flag rather than the
// struct field, because that message reaches an operator running
// `eshu admin repository retire` and naming the field would not tell them
// what to type.
func Retire(client Client, in RetireInput) (any, error) {
	if strings.TrimSpace(in.Reason) == "" {
		return nil, fmt.Errorf("--reason is required and must explain why the retirement is safe")
	}
	idempotencyKey := in.IdempotencyKey
	if strings.TrimSpace(idempotencyKey) == "" {
		generated, err := NewRetireIdempotencyKey()
		if err != nil {
			return nil, err
		}
		idempotencyKey = generated
	}
	body := map[string]any{
		"repositories":    in.Repositories,
		"reason":          in.Reason,
		"idempotency_key": idempotencyKey,
	}
	var result any
	if err := client.Post("/api/v0/admin/repository-retirements", body, &result); err != nil {
		return nil, err //nolint:wrapcheck // Client's error is already the operator's message; cmd/eshu prints it verbatim and wrapping would prepend a second prefix.
	}
	return result, nil
}

// NewRetireIdempotencyKey returns a random key so repeated CLI invocations
// do not accidentally collide while a single invocation stays retry-safe.
// The cobra wrapper calls it before the POST and prints the key, so the
// operator can retry with it even when the call fails after the fence
// commits; the Retire fallback below covers library callers.
func NewRetireIdempotencyKey() (string, error) {
	buf := make([]byte, 16)
	if _, err := rand.Read(buf); err != nil {
		return "", fmt.Errorf("generate idempotency key: %w", err)
	}
	return "cli-retire-" + hex.EncodeToString(buf), nil
}
