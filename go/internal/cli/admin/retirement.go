package admin

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"strings"
)

// RetireRepositoriesInput carries the selectors, the justification, and the
// key for RetireRepositories. Reason is mandatory; IdempotencyKey falls
// back to a generated key when blank. Callers that print the key before
// the call (the cobra wrapper does) pass an explicit key so the operator
// always knows it, even when the call fails after the fence commits.
type RetireRepositoriesInput struct {
	// Repositories holds the repository selectors (repository ID, scope ID,
	// name, slug, or path); at least one is required.
	Repositories []string
	// Reason must be non-blank: RetireRepositories rejects the request
	// before any HTTP call otherwise.
	Reason string
	// IdempotencyKey is generated by newRetireIdempotencyKey when blank.
	IdempotencyKey string
}

// RetireRepositories triggers the operator retirement for the named
// repositories and returns the decoded response body. It refuses a blank
// Reason or an empty Repositories list, and generates an idempotency key
// when the caller supplies none, so a retried invocation stays safe.
//
// The blank-Reason error names the `--reason` CLI flag rather than the
// struct field, because that message reaches an operator running
// `eshu admin retire-repositories` and naming the field would not tell them
// what to type.
func RetireRepositories(client Client, in RetireRepositoriesInput) (any, error) {
	if strings.TrimSpace(in.Reason) == "" {
		return nil, fmt.Errorf("--reason is required and must explain why the retirement is safe")
	}
	if len(in.Repositories) == 0 {
		return nil, fmt.Errorf("--repository is required: name at least one repository to retire")
	}
	idempotencyKey := in.IdempotencyKey
	if strings.TrimSpace(idempotencyKey) == "" {
		generated, err := NewRetireIdempotencyKey()
		if err != nil {
			return nil, err
		}
		idempotencyKey = generated
	}

	body := map[string]any{
		"repositories":    in.Repositories,
		"reason":          in.Reason,
		"idempotency_key": idempotencyKey,
	}
	var result any
	if err := client.Post("/api/v0/admin/repositories/retire", body, &result); err != nil {
		return nil, err //nolint:wrapcheck // Client's error is already the operator's message; cmd/eshu prints it verbatim and wrapping would prepend a second prefix.
	}
	return result, nil
}

// NewRetireIdempotencyKey returns a random key so repeated CLI invocations
// do not accidentally collide while a single invocation stays retry-safe.
// The cobra wrapper calls it before the POST and prints the key, so the
// operator can retry with it even when the call fails after the fence
// commits; the RetireRepositories fallback covers library callers.
func NewRetireIdempotencyKey() (string, error) {
	buf := make([]byte, 16)
	if _, err := rand.Read(buf); err != nil {
		return "", fmt.Errorf("generate idempotency key: %w", err)
	}
	return "cli-retire-" + hex.EncodeToString(buf), nil
}
