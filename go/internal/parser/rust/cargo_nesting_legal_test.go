func writeCargoFile(t *testing.T, path, body string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
}

// TestCargoDeepButLegalManifestStillParses keeps the guard honest about false
// positives: six levels of inline tables and arrays is deeper than any real
// Cargo file and must still produce its dependency row.
func TestCargoDeepButLegalManifestStillParses(t *testing.T) {
	t.Parallel()
	repoRoot := t.TempDir()
	path := filepath.Join(repoRoot, "Cargo.toml")
	writeCargoFile(t, path, `[package]
name = "x"
version = "0.1.0"

[target.'cfg(any(unix, target_os = "wasi"))'.dependencies]
deep = { version = "1.2", metadata = { a = { b = { c = { d = ["[[{{"] } } } } }
`)
	payload, err := ParseCargoDependencyFile(repoRoot, path, false)
	if err != nil {
		t.Fatalf("ParseCargoDependencyFile() error = %v, want nil", err)
	}
	rows, _ := payload["variables"].([]map[string]any)
	if len(rows) != 1 || rows[0]["name"] != "deep" || rows[0]["value"] != "1.2" {
		t.Fatalf("rows = %#v, want one deep 1.2 row", rows)
	}
}

// TestCargoGuardErrorsAreTyped proves a too-deep or unterminated file fails
// through the normal parse error path with an error a caller can classify.
func TestCargoGuardErrorsAreTyped(t *testing.T) {
	t.Parallel()
	over := "a = " + strings.Repeat("[", cargoMaxNesting+1) + strings.Repeat("]", cargoMaxNesting+1) + "\n"
	for name, tc := range map[string]struct {
		file, body string
		want       error
	}{
		"manifest one level over": {"Cargo.toml", "[dependencies]\n" + over, nesting.ErrTooDeep},
		"lockfile one level over": {"Cargo.lock", "version = 3\n" + over, nesting.ErrTooDeep},
		"manifest unterminated":   {"Cargo.toml", "[dependencies]\nserde = \"1.0\n", nesting.ErrUnterminatedString},
		"lockfile unterminated":   {"Cargo.lock", "[[package]]\nname = '''a\n", nesting.ErrUnterminatedString},
	} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			repoRoot := t.TempDir()
			path := filepath.Join(repoRoot, tc.file)
			writeCargoFile(t, path, tc.body)
			payload, err := ParseCargoDependencyFile(repoRoot, path, false)
			if !errors.Is(err, tc.want) {
				t.Fatalf("ParseCargoDependencyFile() error = %v, want %v", err, tc.want)
			}
			if payload != nil {
				t.Fatalf("payload = %#v, want nil on a rejected file", payload)
			}
			if !strings.Contains(err.Error(), tc.file) {
				t.Fatalf("error %q does not name the file", err)
			}
		})
	}
}

// TestCargoManifestAtLimitStillParses pins the inclusive limit through the
// real call site: depth exactly cargoMaxNesting decodes.
func TestCargoManifestAtLimitStillParses(t *testing.T) {
	t.Parallel()
	repoRoot := t.TempDir()
	path := filepath.Join(repoRoot, "Cargo.toml")
	atLimit := strings.Repeat("[", cargoMaxNesting) + strings.Repeat("]", cargoMaxNesting)
	writeCargoFile(t, path, "[package]\nname = \"x\"\nnested = "+atLimit+"\n\n[dependencies]\nserde = \"1\"\n")
	payload, err := ParseCargoDependencyFile(repoRoot, path, false)
	if err != nil {
		t.Fatalf("ParseCargoDependencyFile() error = %v, want nil at the limit", err)
	}
	if rows, _ := payload["variables"].([]map[string]any); len(rows) != 1 {
		t.Fatalf("rows = %#v, want the serde row", rows)
	}
}

// TestCargoLargeLegalLockfileMatchesUnguardedDecode is the differential: a
// 50,000-package Cargo.lock yields exactly the rows an unguarded go-toml
// decode yields, so the guard changes nothing for legal files.
func TestCargoLargeLegalLockfileMatchesUnguardedDecode(t *testing.T) {
	t.Parallel()
	var b strings.Builder
	b.WriteString("# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \"crate-0\",\n]\n")
	const packages = 50_000
	for i := range packages {
		fmt.Fprintf(&b, "\n[[package]]\nname = \"crate-%d\"\nversion = \"1.%d.0\"\n", i, i%40)
		b.WriteString("source = \"registry+https://github.com/rust-lang/crates.io-index\"\n")
		fmt.Fprintf(&b, "checksum = \"%064x\"\n", i)
		if i+1 < packages && i%100 != 99 {
			fmt.Fprintf(&b, "dependencies = [\n \"crate-%d\",\n]\n", i+1)
		}
	}
	source := b.String()
	repoRoot := t.TempDir()
	path := filepath.Join(repoRoot, "Cargo.lock")
	writeCargoFile(t, path, source)

	payload, err := ParseCargoDependencyFile(repoRoot, path, false)
	if err != nil {
		t.Fatalf("ParseCargoDependencyFile() error = %v, want nil", err)
	}
	var lock cargoLockDocument
	if err := toml.Unmarshal([]byte(source), &lock); err != nil {
		t.Fatalf("unguarded decode error = %v", err)
	}
	want := cargoLockDependencyRows(repoRoot, path, lock)
	got, _ := payload["variables"].([]map[string]any)
	if len(got) != packages {
		t.Fatalf("rows = %d, want %d", len(got), packages)
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatal("guarded rows differ from the unguarded decode")
	}
}
