// hostileDepth is one million levels. go-toml v2.3.1 overflows the goroutine
// stack at about 885,000 '[' or 483,000 inline tables, and at one million
// dotted-key segments.
const hostileDepth = 1_000_000

// guardAllocCeiling bounds what Check may allocate on any input: its frame
// stack is capped at limit+1 entries and the error is one small value.
const guardAllocCeiling = 16 << 10

func hostileDocuments() map[string][]byte {
	dotted := strings.Repeat("a.", hostileDepth) + "a"
	return map[string][]byte{
		"arrays unterminated": []byte("a = " + strings.Repeat("[", hostileDepth)),
		"arrays closed":       []byte("a = " + strings.Repeat("[", hostileDepth) + strings.Repeat("]", hostileDepth)),
		"inline tables":       []byte("a = " + strings.Repeat("{a=", hostileDepth)),
		"dotted key":          []byte(dotted + " = 1\n"),
		"dotted header":       []byte("[" + dotted + "]\n"),
		"dotted array header": []byte("[[" + dotted + "]]\n"),
		"mixed":               []byte("a = " + strings.Repeat("[{b.c=", hostileDepth/3)),
	}
}

// TestCheckRejectsHostileDepthWithBoundedAllocation is the byte ceiling at
// one million levels. It measures allocated bytes, not time.
func TestCheckRejectsHostileDepthWithBoundedAllocation(t *testing.T) {
	for name, doc := range hostileDocuments() {
		t.Run(name, func(t *testing.T) {
			var err error
			got := allocatedBytes(func() { err = Check(doc, 64) })
			if !errors.Is(err, ErrTooDeep) {
				t.Fatalf("Check() = %v, want ErrTooDeep", err)
			}
			if got > guardAllocCeiling {
				t.Fatalf("Check() allocated %d bytes per op, want <= %d", got, guardAllocCeiling)
			}
		})
	}
}

// TestCheckAllocationIsFlatOnLegalLockfile proves the guard does not scale
// with a large legal file: a Cargo.lock of about 1 MB costs only the frame
// stack.
func TestCheckAllocationIsFlatOnLegalLockfile(t *testing.T) {
	doc := legalLockfile(10_000)
	if len(doc) < 1<<20 {
		t.Fatalf("fixture is %d bytes, want at least 1 MiB", len(doc))
	}
	var err error
	got := allocatedBytes(func() { err = Check(doc, 64) })
	if err != nil {
		t.Fatalf("Check() = %v, want nil", err)
	}
	if got > 1<<10 {
		t.Fatalf("Check() allocated %d bytes per op on a legal lockfile, want <= 1024", got)
	}
}

// TestAcceptedDepthDecodesWithBoundedAllocation is the differential half of
// the contract: a document right at the limit passes the guard and go-toml
// then decodes it without trouble and with a small, bounded allocation.
func TestAcceptedDepthDecodesWithBoundedAllocation(t *testing.T) {
	const limit = 64
	for name, doc := range map[string][]byte{
		"arrays":        []byte("a = " + strings.Repeat("[", limit) + strings.Repeat("]", limit) + "\n"),
		"inline tables": []byte("a = " + strings.Repeat("{a=", limit-1) + "{}" + strings.Repeat("}", limit-1) + "\n"),
		"dotted key":    []byte(strings.Repeat("a.", limit) + "a = 1\n"),
		"header":        []byte("[" + strings.Repeat("a.", limit/2) + "a]\n" + strings.Repeat("b.", limit/2) + "b = 1\n"),
	} {
		t.Run(name, func(t *testing.T) {
			if err := Check(doc, limit); err != nil {
				t.Fatalf("Check() = %v, want nil at the limit", err)
			}
			runtime.GC()
			var before, after runtime.MemStats
			runtime.ReadMemStats(&before)
			var decoded map[string]any
			err := toml.Unmarshal(doc, &decoded)
			runtime.ReadMemStats(&after)
			if err != nil {
				t.Fatalf("go-toml error = %v, want nil", err)
			}
			if got := after.TotalAlloc - before.TotalAlloc; got > 1<<20 {
				t.Fatalf("go-toml allocated %d bytes at the limit, want <= 1 MiB", got)
			}
		})
	}
}

// allocatedBytes returns the mean bytes fn allocates over a few runs. It
// reads the runtime's cumulative allocation counter, so it measures bytes,
// not time.
func allocatedBytes(fn func()) uint64 {
	const runs = 4
	fn() // warm up once so lazy runtime setup is not charged to the guard
	var before, after runtime.MemStats
	runtime.ReadMemStats(&before)
	for range runs {
		fn()
	}
	runtime.ReadMemStats(&after)
	return (after.TotalAlloc - before.TotalAlloc) / runs
}

// legalLockfile returns a Cargo.lock shaped document with n packages.
func legalLockfile(n int) []byte {
	var b strings.Builder
	b.WriteString("# This file is automatically @generated by Cargo.\nversion = 3\n")
	for i := range n {
		fmt.Fprintf(&b, "\n[[package]]\nname = \"crate-%d\"\nversion = \"1.%d.0\"\n", i, i%50)
		b.WriteString("source = \"registry+https://github.com/rust-lang/crates.io-index\"\n")
		fmt.Fprintf(&b, "checksum = \"%064x\"\n", i)
		if i > 0 {
			fmt.Fprintf(&b, "dependencies = [\n \"crate-%d\",\n \"crate-%d 1.0.0\",\n]\n", i-1, i/2)
		}
	}
	return []byte(b.String())
}

// BenchmarkCheckLegalLockfile measures the guard on a legal Cargo.lock of
// about 1 MB, the cost every Cargo parse now pays before decoding.
func BenchmarkCheckLegalLockfile(b *testing.B) {
	doc := legalLockfile(10_000)
	b.SetBytes(int64(len(doc)))
	b.ReportAllocs()
	for b.Loop() {
		if err := Check(doc, 64); err != nil {
			b.Fatal(err)
		}
	}
}

// BenchmarkCheckBoundsLegalLockfile is the same file under CheckBounds, the
// call Cargo parsing makes: depth plus key work.
func BenchmarkCheckBoundsLegalLockfile(b *testing.B) {
	doc := legalLockfile(10_000)
	b.SetBytes(int64(len(doc)))
	b.ReportAllocs()
	for b.Loop() {
		if err := CheckBounds(doc, Bounds{Depth: 64, KeyWork: 25_000_000}); err != nil {
			b.Fatal(err)
		}
	}
}

// BenchmarkDecodeLegalLockfile is the go-toml decode of the same file, the
// baseline the guard's cost is compared against.
func BenchmarkDecodeLegalLockfile(b *testing.B) {
	doc := legalLockfile(10_000)
	type lock struct {
		Packages []struct {
			Name         string   `toml:"name"`
			Version      string   `toml:"version"`
			Source       string   `toml:"source"`
			Dependencies []string `toml:"dependencies"`
		} `toml:"package"`
	}
	b.SetBytes(int64(len(doc)))
	b.ReportAllocs()
	for b.Loop() {
		var decoded lock
		if err := toml.Unmarshal(doc, &decoded); err != nil {
			b.Fatal(err)
		}
	}
}
