// TestClassifyDeadCodeResults proves the classifier stamps unsupported
// languages, exactness blockers, weak incoming edges, hidden consumers,
// and derived-candidate languages onto their distinct verdicts.
func TestClassifyDeadCodeResults(t *testing.T) {
	t.Parallel()

	results := []map[string]any{
		{"entity_id": "e-go", "language": "go"},
		{"entity_id": "e-brain", "language": "brainfuck"},
		{"entity_id": "e-blocked", "language": "go", "metadata": map[string]any{"exactness_blockers": []any{"dynamic_call"}}},
		{"entity_id": "e-weak", "language": "go", "weak_incoming_only": true},
		{"entity_id": "e-hidden", "language": "go", "permission_hidden_consumer": true},
		{"entity_id": "e-groovy", "language": "groovy"},
	}
	ClassifyDeadCodeResults(results, map[string]*querycontract.EntityContent{})

	want := map[string]string{
		"e-go":      DeadCodeClassificationUnused,
		"e-brain":   "unsupported_language",
		"e-blocked": DeadCodeClassificationAmbiguous,
		"e-weak":    DeadCodeClassificationAmbiguous,
		"e-hidden":  DeadCodeClassificationAmbiguous,
		"e-groovy":  "derived_candidate_only",
	}
	for _, result := range results {
		id := result["entity_id"].(string)
		if got := result["classification"]; got != want[id] {
			t.Errorf("%s classification = %v, want %q", id, got, want[id])
		}
	}
}

// TestDeadCodeWeakIncomingAmbiguityReason proves the weak-incoming
// reason names the triggering method and defaults it when unrecorded.
func TestDeadCodeWeakIncomingAmbiguityReason(t *testing.T) {
	t.Parallel()

	reason, ok := DeadCodeWeakIncomingAmbiguityReason(map[string]any{
		"weak_incoming_only": true, "weak_incoming_method": "repo_unique_name",
	})
	if !ok {
		t.Fatal("weak-incoming result must report a reason")
	}
	if reason == "" {
		t.Error("weak-incoming reason must not be empty")
	}
	if _, ok := DeadCodeWeakIncomingAmbiguityReason(map[string]any{}); ok {
		t.Error("strong result must not report a weak-incoming reason")
	}
	if !DeadCodeResultHasHiddenConsumer(map[string]any{"permission_hidden_consumer": true}) {
		t.Error("hidden-consumer marker must be detected")
	}
}

// TestFilterResultsByDecoratorExclusions proves excluded decorators
// drop their results while undecorated and unlisted results survive.
func TestFilterResultsByDecoratorExclusions(t *testing.T) {
	t.Parallel()

	results := []map[string]any{
		{"entity_id": "e1", "metadata": map[string]any{"decorators": []any{"@generated"}}},
		{"entity_id": "e2", "metadata": map[string]any{"decorators": []any{"custom"}}},
		{"entity_id": "e3"},
	}
	filtered := FilterResultsByDecoratorExclusions(results, []string{"@generated"})
	if len(filtered) != 2 {
		t.Fatalf("len(filtered) = %d, want 2", len(filtered))
	}
	if filtered[0]["entity_id"] != "e2" {
		t.Errorf("survivors = %v and %v, want e2 and e3", filtered[0]["entity_id"], filtered[1]["entity_id"])
	}
	if got := FilterResultsByDecoratorExclusions(results, nil); len(got) != 3 {
		t.Errorf("empty exclusion list must pass %d rows through, got %d", len(results), len(got))
	}
	if NormalizeDecoratorName("  @cached  ") != "cached" {
		t.Errorf("NormalizeDecoratorName must trim and strip @")
	}
}

// TestDeadCodeIsTestFile proves test-file detection across Go, JS,
// Python, and Java source-set layouts without flagging plain sources.
func TestDeadCodeIsTestFile(t *testing.T) {
	t.Parallel()

	for _, path := range []string{
		"pkg/a_test.go",
		"src/__tests__/a.ts",
		"cypress/e2e/a.cy.ts",
		"tests/test_a.py",
		"pkg/foo_test.py",
		"pkg/a.spec.ts",
		"src/test/java/Foo.java",
		"a.config.ts",
	} {
		entity := &querycontract.EntityContent{RelativePath: path}
		if !DeadCodeIsTestFile(map[string]any{}, entity) {
			t.Errorf("%q must read as a test file", path)
		}
	}
	plain := &querycontract.EntityContent{RelativePath: "pkg/server.go"}
	if DeadCodeIsTestFile(map[string]any{}, plain) {
		t.Error("pkg/server.go must not read as a test file")
	}
	if DeadCodeIsTestFile(map[string]any{}, nil) {
		t.Error("nil entity must not read as a test file")
	}
}

// TestDeadCodeIsGeneratedCode proves generated-code detection across
// path markers, file suffixes, and source-cache banners.
func TestDeadCodeIsGeneratedCode(t *testing.T) {
	t.Parallel()

	for _, path := range []string{"pkg/gen/a.go", "pkg/types.pb.go", "pkg/api.gen.go", "pkg/model_generated.go"} {
		entity := &querycontract.EntityContent{RelativePath: path}
		if !DeadCodeIsGeneratedCode(map[string]any{}, entity) {
			t.Errorf("%q must read as generated code", path)
		}
	}
	banner := &querycontract.EntityContent{
		RelativePath: "pkg/a.go",
		SourceCache:  "// Code generated by protoc. DO NOT EDIT.",
	}
	if !DeadCodeIsGeneratedCode(map[string]any{}, banner) {
		t.Error("generated banner must read as generated code")
	}
	plain := &querycontract.EntityContent{RelativePath: "pkg/server.go", SourceCache: "package server"}
	if DeadCodeIsGeneratedCode(map[string]any{}, plain) {
		t.Error("plain source must not read as generated code")
	}
}
