// Recompute write side of the #3389 canonical dedup materialization. See
// docs/internal/supply-chain-impact-canonical-dedup-materialization-design.md.
//
// IMPORTANT — read/write parity: the winner selection here MUST stay byte-for-byte
// equivalent to the read-time dedup in
// go/internal/query/supply/chain/impact/findings_queries.go. canonical_key, the
// public finding_id fallback, the has_payload_finding_id tiebreak, the
// suppression_state default are duplicated from that query on purpose
// (cross-package); the severity_bucket CASE is generated by cvss.BucketSQL on
// both sides (#9693), so it is shared rather than copied. The integration parity test
// (winners-recompute output filtered == legacy ROW_NUMBER read) is what guards
// against drift.

// supplyChainImpactWinnerSelectSQL projects one source-owned winner per
// canonical key and overlays the authoritative operator suppression state.
// Source evidence remains the filtering, ordering, and payload authority;
// operator-only keys cannot fabricate findings.
//
// It is the active_facts prefix followed by the body. The keyed resweep (#9805)
// reuses the body unchanged over a keyed active_facts, so the two paths cannot
// drift: supplyChainImpactWinnerSelectSQL is exactly prefix + body.
var supplyChainImpactWinnerSelectSQL = supplyChainImpactWinnerActiveFactsSQL + supplyChainImpactWinnerBodySQL

// supplyChainImpactWinnerActiveFactsSQL opens the full select with the active
// impact facts of every active scope generation.
const supplyChainImpactWinnerActiveFactsSQL = `
WITH active_facts AS NOT MATERIALIZED (
    SELECT fact.*
    FROM fact_records AS fact
    JOIN ingestion_scopes AS scope
      ON scope.scope_id = fact.scope_id
     AND scope.active_generation_id = fact.generation_id
    JOIN scope_generations AS generation
      ON generation.scope_id = fact.scope_id
     AND generation.generation_id = fact.generation_id
    WHERE fact.fact_kind = 'reducer_supply_chain_impact_finding'
      AND fact.is_tombstone = FALSE
      AND generation.status = 'active'
)`

// supplyChainImpactWinnerBodySQL is the select after the active_facts CTE. It
// starts with the comma that joins it to a preceding WITH clause.
var supplyChainImpactWinnerBodySQL = `,
source_candidates AS (
    SELECT
        fact.fact_id,
        fact.scope_id,
        fact.payload,
        CONCAT_WS('|',
            COALESCE(NULLIF(fact.payload->>'cve_id', ''), NULLIF(fact.payload->>'advisory_id', ''), ''),
            COALESCE(fact.payload->>'advisory_id', ''),
            COALESCE(fact.payload->>'package_id', ''),
            COALESCE(fact.payload->>'purl', ''),
            COALESCE(fact.payload->>'product_criteria', ''),
            COALESCE(fact.payload->>'match_criteria_id', ''),
            COALESCE(fact.payload->>'observed_version', ''),
            COALESCE(fact.payload->>'requested_range', ''),
            COALESCE(fact.payload->>'impact_status', ''),
            COALESCE(fact.payload->>'repository_id', ''),
            COALESCE(fact.payload->>'subject_digest', '')
        ) AS canonical_key,
        COALESCE(
            NULLIF(fact.payload->>'finding_id', ''),
            CONCAT_WS('|',
                COALESCE(NULLIF(fact.payload->>'cve_id', ''), NULLIF(fact.payload->>'advisory_id', ''), ''),
                COALESCE(fact.payload->>'advisory_id', ''),
                COALESCE(fact.payload->>'package_id', ''),
                COALESCE(fact.payload->>'purl', ''),
                COALESCE(fact.payload->>'product_criteria', ''),
                COALESCE(fact.payload->>'match_criteria_id', ''),
                COALESCE(fact.payload->>'observed_version', ''),
                COALESCE(fact.payload->>'requested_range', ''),
                COALESCE(fact.payload->>'impact_status', ''),
                COALESCE(fact.payload->>'repository_id', ''),
                COALESCE(fact.payload->>'subject_digest', '')
            )
        ) AS finding_id,
        COALESCE(NULLIF(fact.payload->>'priority_score', '')::int, 0) AS priority_score,
        CASE WHEN NULLIF(fact.payload->>'finding_id', '') IS NULL THEN 0 ELSE 1 END AS has_payload_finding_id,
        COALESCE(NULLIF(fact.payload->>'suppression_state', ''), 'active') AS suppression_state
    FROM active_facts AS fact
    LEFT JOIN scanner_image_result_fact_classifications AS finding_class
      ON finding_class.finding_fact_id = fact.fact_id
    LEFT JOIN scanner_image_result_fact_associations AS finding_association
      ON finding_association.finding_fact_id = fact.fact_id
    WHERE fact.scope_id <> 'operator:vulnerability_suppressions'
      AND finding_association.finding_fact_id IS NULL
      AND fact.scope_id NOT LIKE 'image://derived/%'
      AND (finding_class.finding_fact_id IS NULL
           OR (finding_class.source_class = 'static' AND finding_class.lifecycle = 'active'))
),
source_ranked AS (
    SELECT source.*,
           COUNT(*) OVER (PARTITION BY canonical_key) AS source_count
    FROM source_candidates AS source
),
source_winners AS (
    SELECT DISTINCT ON (canonical_key) *
    FROM source_ranked
    ORDER BY canonical_key,
             priority_score DESC,
             has_payload_finding_id DESC,
             fact_id ASC
),
operator_candidates AS (
    SELECT
        fact.fact_id,
        fact.payload,
        CONCAT_WS('|',
            COALESCE(NULLIF(fact.payload->>'cve_id', ''), NULLIF(fact.payload->>'advisory_id', ''), ''),
            COALESCE(fact.payload->>'advisory_id', ''),
            COALESCE(fact.payload->>'package_id', ''),
            COALESCE(fact.payload->>'purl', ''),
            COALESCE(fact.payload->>'product_criteria', ''),
            COALESCE(fact.payload->>'match_criteria_id', ''),
            COALESCE(fact.payload->>'observed_version', ''),
            COALESCE(fact.payload->>'requested_range', ''),
            COALESCE(fact.payload->>'impact_status', ''),
            COALESCE(fact.payload->>'repository_id', ''),
            COALESCE(fact.payload->>'subject_digest', '')
        ) AS canonical_key,
        COALESCE(NULLIF(fact.payload->>'suppression_state', ''), 'active') AS suppression_state,
        COALESCE(NULLIF(fact.payload->>'priority_score', '')::int, 0) AS priority_score,
        CASE WHEN NULLIF(fact.payload->>'finding_id', '') IS NULL THEN 0 ELSE 1 END AS has_payload_finding_id
    FROM active_facts AS fact
    WHERE fact.scope_id = 'operator:vulnerability_suppressions'
      AND COALESCE(NULLIF(fact.payload->>'suppression_state', ''), 'active') <> 'active'
),
operator_overrides AS (
    SELECT DISTINCT ON (canonical_key) *
    FROM operator_candidates
    ORDER BY canonical_key,
             priority_score DESC,
             has_payload_finding_id DESC,
             fact_id ASC
)
SELECT
    source.canonical_key,
    source.fact_id AS winner_fact_id,
    source.scope_id AS winner_scope_id,
    source.finding_id,
    source.priority_score,
    source.source_count,
    COALESCE(source.payload->>'impact_status', '') AS impact_status,
    COALESCE(source.payload->>'ecosystem', '') AS ecosystem,
    ` + cvss.BucketSQL("source.payload") + ` AS severity_bucket,
    COALESCE(source.payload->>'repository_id', '') AS repository_id,
    COALESCE(source.payload->>'cve_id', '') AS cve_id,
    COALESCE(source.payload->>'advisory_id', '') AS advisory_id,
    COALESCE(source.payload->>'package_id', '') AS package_id,
    COALESCE(source.payload->>'subject_digest', '') AS subject_digest,
    COALESCE(source.payload->>'image_ref', '') AS image_ref,
    COALESCE(source.payload->>'priority_bucket', '') AS priority_bucket,
    COALESCE(source.payload->>'detection_profile', '') AS detection_profile,
    COALESCE(source.payload->>'observed_version', '') AS observed_version,
    COALESCE(source.payload->>'match_reason', '') AS match_reason,
    COALESCE(override.suppression_state, source.suppression_state) AS suppression_state,
    CASE
        WHEN override.fact_id IS NULL
          OR NULLIF(override.payload #>> '{suppression,expires_at}', '') IS NULL
        THEN NULL
        WHEN pg_input_is_valid(
            override.payload #>> '{suppression,expires_at}',
            'timestamp with time zone'
        )
        THEN (override.payload #>> '{suppression,expires_at}')::timestamptz
        ELSE '-infinity'::timestamptz
    END AS suppression_expires_at,
    COALESCE(source.payload->'service_ids', '[]'::jsonb) AS service_ids,
    COALESCE(source.payload->'workload_ids', '[]'::jsonb) AS workload_ids,
    COALESCE(source.payload->'environments', '[]'::jsonb) AS environments
FROM source_winners AS source
LEFT JOIN operator_overrides AS override
  ON override.canonical_key = source.canonical_key
`

// SupplyChainImpactBeginner adapts a postgres Beginner (for example the
// instrumented reducer DB) into the reducer's supply-chain impact transaction
// surface (#6831), so the writer commits its conflict-domain lock, finding
// upsert, and superseded-finding retraction atomically over the shared
// instrumented connection. Mirrors AWSCloudRuntimeDriftAdmissionBeginner; it lives beside the winners store to keep this directory at its dirgate-pinned file count.
type SupplyChainImpactBeginner struct {
	Beginner db.Beginner
	// Instruments counts the winners dirty-log rows the writer transaction
	// appends (#9805). Nil is safe and records nothing.
	Instruments *telemetry.Instruments
}

// BeginSupplyChainImpactTx opens a transaction wrapped in the reducer's
// supply-chain impact writer surface.
func (b SupplyChainImpactBeginner) BeginSupplyChainImpactTx(
	ctx context.Context,
) (supplychaincore.SupplyChainImpactTx, error) {
	tx, err := b.Beginner.Begin(ctx)
	if err != nil {
		return nil, err
	}
	return &supplyChainImpactTx{tx: tx, instruments: b.Instruments}, nil
}

type supplyChainImpactTx struct {
	tx          db.Transaction
	instruments *telemetry.Instruments

	// authorizedPublicationHash pins the exact set Authorize accepted, so
	// Publish rejects a different set in the same transaction.
	authorizedPublicationHash [32]byte
	authorizedPublication     bool
}

var (
	_ supplychaincore.ProtectedScanImpactPublisher  = (*supplyChainImpactTx)(nil)
	_ supplychaincore.ProtectedScanImpactAuthorizer = (*supplyChainImpactTx)(nil)
)

// supplyChainImpactPolicyPinsQuery reads the current protected policy pins
// inside the caller's transaction. The runtime-writer profile holds SELECT
// on the policy state by inventory; the DEFINER entrypoints recheck them
// against the singleton under lock.
const supplyChainImpactPolicyPinsQuery = `SELECT policy_revision, database_identity
FROM eshu_security.role_policy_state WHERE singleton`

// authorizeImpactPublicationQuery and publishImpactPublicationQuery call the
// protected publication entrypoints (#9299). Explicit casts keep pgx from
// inferring text for the jsonb and uuid parameters.
const authorizeImpactPublicationQuery = `SELECT eshu_security.authorize_impact_publication_v1(
$1,$2,$3,$4::jsonb,$5,$6::uuid)`

const publishImpactPublicationQuery = `SELECT eshu_security.publish_impact_publication_v1(
$1,$2,$3,$4::jsonb,$5,$6::uuid)`

// AuthorizeProtectedScanImpactResults locks and validates the complete
// authorized source and advisory set before the impact conflict lock. The
// database retains every SHARE lock until this transaction commits or rolls
// back.
func (t *supplyChainImpactTx) AuthorizeProtectedScanImpactResults(
	ctx context.Context,
	set supplychaincore.ProtectedScanImpactPublicationSet,
) error {
	if t.tx == nil {
		return fmt.Errorf("protected impact publication transaction is unavailable")
	}
	if !set.CompleteSet {
		return fmt.Errorf("protected impact publication set is not complete")
	}
	document, err := supplychaincore.MarshalImpactPublicationSetDocument(set)
	if err != nil {
		return fmt.Errorf("marshal protected impact publication set: %w", err)
	}
	revision, identity, err := t.protectedPolicyPins(ctx)
	if err != nil {
		return err
	}
	if _, err := t.tx.ExecContext(ctx, authorizeImpactPublicationQuery,
		set.ImpactScopeID, set.ImpactGenerationID, set.ImpactFencingToken,
		string(document), revision, identity); err != nil {
		return fmt.Errorf("authorize protected scan impact results: %w", err)
	}
	t.authorizedPublicationHash = sha256.Sum256(document)
	t.authorizedPublication = true
	return nil
}

// PublishProtectedScanImpactResults persists the authorized set inside the
// transaction that wrote its finding facts. A set that differs from the
// authorized one is rejected before any publication row is touched.
func (t *supplyChainImpactTx) PublishProtectedScanImpactResults(
	ctx context.Context,
	set supplychaincore.ProtectedScanImpactPublicationSet,
) error {
	if t.tx == nil {
		return fmt.Errorf("protected impact publication transaction is unavailable")
	}
	document, err := supplychaincore.MarshalImpactPublicationSetDocument(set)
	if err != nil {
		return fmt.Errorf("marshal protected impact publication set: %w", err)
	}
	if !t.authorizedPublication || t.authorizedPublicationHash != sha256.Sum256(document) {
		return fmt.Errorf("protected impact publication set differs from the authorized set")
	}
	revision, identity, err := t.protectedPolicyPins(ctx)
	if err != nil {
		return err
	}
	if _, err := t.tx.ExecContext(ctx, publishImpactPublicationQuery,
		set.ImpactScopeID, set.ImpactGenerationID, set.ImpactFencingToken,
		string(document), revision, identity); err != nil {
		return fmt.Errorf("publish protected scan impact results: %w", err)
	}
	return nil
}

func (t *supplyChainImpactTx) protectedPolicyPins(ctx context.Context) (int64, string, error) {
	rows, err := t.tx.QueryContext(ctx, supplyChainImpactPolicyPinsQuery)
	if err != nil {
		return 0, "", fmt.Errorf("read protected policy pins: %w", err)
	}
	defer func() { _ = rows.Close() }()
	if !rows.Next() {
		if err := rows.Err(); err != nil {
			return 0, "", fmt.Errorf("read protected policy pins: %w", err)
		}
		return 0, "", errors.New("protected policy state is absent")
	}
	var revision int64
	var identity string
	if err := rows.Scan(&revision, &identity); err != nil {
		_ = rows.Close()
		return 0, "", fmt.Errorf("read protected policy pins: %w", err)
	}
	return revision, identity, rows.Err()
}

func (t supplyChainImpactTx) ExecContext(
	ctx context.Context,
	query string,
	args ...any,
) (sql.Result, error) {
	return t.tx.ExecContext(ctx, query, args...)
}

// QueryContext runs a read inside the write transaction.
func (t supplyChainImpactTx) QueryContext(
	ctx context.Context,
	query string,
	args ...any,
) (supplychaincore.SupplyChainImpactRows, error) {
	rows, err := t.tx.QueryContext(ctx, query, args...)
	if err != nil {
		return nil, err
	}
	return rows, nil
}

func (t supplyChainImpactTx) Commit() error   { return t.tx.Commit() }
func (t supplyChainImpactTx) Rollback() error { return t.tx.Rollback() }

// supplyChainImpactFencingTokenSequence is the Postgres sequence backing
// PostgresSupplyChainImpactFencingTokenIssuer (migration
// 154_supply_chain_impact_write_admission.sql).
// #nosec G101 -- sequence name, not a credential
const supplyChainImpactFencingTokenSequence = "supply_chain_impact_fencing_token_seq"

// supplyChainImpactNextFencingTokenQuery issues the next value from the shared
// sequence. A plain SELECT nextval(...): the sequence is the ordering primitive
// itself, so there is nothing to upsert or conflict-guard, and Postgres already
// guarantees nextval() never returns one value to two concurrent callers.
const supplyChainImpactNextFencingTokenQuery = `SELECT nextval('` + supplyChainImpactFencingTokenSequence + `')`

// PostgresSupplyChainImpactFencingTokenIssuer implements
// supplychain/core.SupplyChainImpactFencingTokenIssuer (#7142) over a plain
// query connection. No transaction is needed: a sequence's nextval() is not
// transactional, and Postgres does not roll back sequence advances when a
// caller aborts, so a pass that later defers or fails leaves a harmless gap in
// an ordering-only value.
type PostgresSupplyChainImpactFencingTokenIssuer struct {
	DB db.Queryer
}

// listActiveFindingCVEIDsQuery returns the distinct non-blank CVE ids on
// active canonical winners. Active means suppression_state 'active'; anything
// else is an operator-suppressed finding and carries no EPSS enrichment.
// The query returns every distinct id including GHSA and other schemes: the
// coordinator normalizes CVE shape and counts exclusions, so the exclusion
// evidence stays observable instead of vanishing in the store.
const listActiveFindingCVEIDsQuery = `
SELECT DISTINCT cve_id
    FROM supply_chain_impact_canonical_winners
    WHERE suppression_state = 'active'
      AND cve_id <> ''
    ORDER BY cve_id
`

// ListActiveFindingCVEIDs returns the distinct non-blank CVE ids on active
// canonical winners, in sorted order (eshu-hq/eshu#9876). It feeds the
// findings-derived EPSS derivation, which keeps CVE-shaped ids and counts
// the rest as exclusions.
func (s FactStore) ListActiveFindingCVEIDs(ctx context.Context) ([]string, error) {
	if s.database == nil {
		return nil, fmt.Errorf("fact store database is required")
	}
	rows, err := s.database.QueryContext(ctx, listActiveFindingCVEIDsQuery)
	if err != nil {
		return nil, fmt.Errorf("list active finding CVE ids: %w", err)
	}
	defer func() { _ = rows.Close() }()

	ids := make([]string, 0, 512)
	for rows.Next() {
		var id string
		if err := rows.Scan(&id); err != nil {
			return nil, fmt.Errorf("list active finding CVE ids scan: %w", err)
		}
		if id == "" {
			continue
		}
		ids = append(ids, id)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("list active finding CVE ids: %w", err)
	}
	return ids, nil
}

// NextSupplyChainImpactFencingToken returns the next value in issuance order.
// SupplyChainImpactHandler.Handle must call it at evidence-read time, before
// the evidence load, not at write-commit time (see
// SupplyChainImpactFencingTokenIssuer).
func (i PostgresSupplyChainImpactFencingTokenIssuer) NextSupplyChainImpactFencingToken(
	ctx context.Context,
) (int64, error) {
	if i.DB == nil {
		return 0, errors.New("supply chain impact fencing token database is required")
	}
	rows, err := i.DB.QueryContext(ctx, supplyChainImpactNextFencingTokenQuery)
	if err != nil {
		return 0, fmt.Errorf("supply chain impact next fencing token: %w", err)
	}
	defer func() { _ = rows.Close() }()

	if !rows.Next() {
		if err := rows.Err(); err != nil {
			return 0, fmt.Errorf("supply chain impact next fencing token: %w", err)
		}
		return 0, errors.New("supply chain impact next fencing token: missing row")
	}
	var token int64
	if err := rows.Scan(&token); err != nil {
		return 0, fmt.Errorf("supply chain impact next fencing token: scan: %w", err)
	}
	if err := rows.Err(); err != nil {
		return 0, fmt.Errorf("supply chain impact next fencing token: %w", err)
	}
	return token, nil
}
