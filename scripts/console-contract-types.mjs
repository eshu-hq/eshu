#!/usr/bin/env node
// Generates TypeScript wire types for the console Home reads from the
// committed OpenAPI snapshot (apps/console/src/api/contracts/homeContracts.json,
// itself pinned to the served spec by the Go test
// TestConsoleHomeContractsSnapshotIsCurrent). One file per route under
// apps/console/src/api/contracts/wire/; homeContracts.test.ts fails when a
// committed file drifts from this renderer's output.
//
//   node scripts/console-contract-types.mjs          # rewrite wire/*.ts
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const contractsJsonPath = resolve(
  here,
  "../apps/console/src/api/contracts/homeContracts.json",
);
export const contractTypesDir = resolve(here, "../apps/console/src/api/contracts/wire");

export function typeNameForRoute(route) {
  const path = route.split(" ")[1].replace("/api/v0/", "");
  const words = path.split(/[^a-zA-Z0-9]+/).filter(Boolean);
  return words.map((w) => w[0].toUpperCase() + w.slice(1)).join("") + "Wire";
}

function typesOf(schema) {
  const t = schema.type;
  return Array.isArray(t) ? t : t ? [t] : [];
}

function render(schema, indent) {
  if (!schema || typeof schema !== "object") return "unknown";
  const variants = schema.oneOf ?? schema.anyOf;
  if (variants) {
    const body = variants.map((v) => render(v, indent)).join(" | ");
    return schema.nullable ? `${body} | null` : body;
  }
  if (schema.allOf) {
    return schema.allOf.map((v) => render(v, indent)).join(" & ");
  }
  const types = typesOf(schema);
  const nullable = schema.nullable === true || types.includes("null");
  const parts = [];
  for (const type of types.length ? types : ["unknown"]) {
    if (type === "null") continue;
    parts.push(renderOne(schema, type, indent));
  }
  if (parts.length === 0) parts.push("unknown");
  if (nullable) parts.push("null");
  return parts.join(" | ");
}

function renderOne(schema, type, indent) {
  if (schema.enum && type !== "object" && type !== "array") {
    return (
      schema.enum
        .filter((v) => v !== null)
        .map((v) => JSON.stringify(v))
        .join(" | ") || "never"
    );
  }
  switch (type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `ReadonlyArray<${render(schema.items ?? {}, indent)}>`;
    case "object":
      return renderObject(schema, indent);
    default:
      return "unknown";
  }
}

function renderObject(schema, indent) {
  const props = schema.properties ?? {};
  const keys = Object.keys(props).sort();
  const ap = schema.additionalProperties;
  if (keys.length === 0) {
    if (ap && typeof ap === "object" && Object.keys(ap).length > 0) {
      return `Readonly<Record<string, ${render(ap, indent)}>>`;
    }
    return "Readonly<Record<string, unknown>>";
  }
  const required = new Set(schema.required ?? []);
  const pad = "  ".repeat(indent + 1);
  const lines = keys.map((key) => {
    const optional = required.has(key) ? "" : "?";
    const name = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
    return `${pad}readonly ${name}${optional}: ${render(props[key], indent + 1)};`;
  });
  return `{\n${lines.join("\n")}\n${"  ".repeat(indent)}}`;
}

const HEADER = [
  "// GENERATED by scripts/console-contract-types.mjs from ../homeContracts.json.",
  "// Do not edit by hand: re-run the Go -update test, then this script.",
  "// Optional (?) marks a key the contract does not list as required.",
  "",
].join("\n");

// renderContractTypes returns { "<TypeName>.ts": source } for every route.
export function renderContractTypes(contracts) {
  const files = {};
  for (const route of Object.keys(contracts).sort()) {
    const name = typeNameForRoute(route);
    files[`${name}.ts`] =
      `${HEADER}\n/** ${route} — 200 response payload. */\nexport type ${name} = ${render(contracts[route], 0)};\n`;
  }
  return files;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const contracts = JSON.parse(readFileSync(contractsJsonPath, "utf8"));
  mkdirSync(contractTypesDir, { recursive: true });
  for (const [file, source] of Object.entries(renderContractTypes(contracts))) {
    writeFileSync(resolve(contractTypesDir, file), source);
  }
  console.log(`wrote ${contractTypesDir}`);
}
