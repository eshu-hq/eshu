#!/usr/bin/env python3
"""Render the live-postgres-readiness generated surfaces (#7859 P1).

All output is LC_ALL=C byte order and idempotent; every emitted Python
module stays under the 500-line file cap or rendering fails closed.
Over-cap packages shard by the committed SHARD_BOUNDARIES name table
(#9149); a shard over budget fails closed naming the boundary to add.
"""

import pathlib
import re

from live_postgres_readiness_gen_scan import fail, packages_of, slug

FRAGMENT_NAMES = (
    "live-tests-readiness.generated.yaml",
    "live-tests-readiness-part2.generated.yaml",
    "live-tests-readiness-part3.generated.yaml",
    "live-tests-readiness-part4.generated.yaml",
)
# Committed lexical cuts keep each file's destination stable as enrollment grows.
FRAGMENT_BOUNDARIES = (
    "go/internal/storage/postgres/backfill/targeted/outcomes_live_test.go",
    "go/internal/storage/postgres/"
    "ingestion_reopen_correlation_fingerprint_interleave_live_test.go",
    "go/internal/storage/postgres/successor_guard_recheck_plan_live_test.go",
)
FRAGMENT_DIR = "specs/live-tests.d/"
MAX_FRAGMENT_LINES = 499


def fragment_paths() -> tuple[str, ...]:
    """Return the exact generator-owned fragment paths in manifest order."""
    return tuple(FRAGMENT_DIR + name for name in FRAGMENT_NAMES)


def fragment_index(path: str) -> int:
    """Assign a proof to its stable lexical range."""
    return sum(path >= boundary for boundary in FRAGMENT_BOUNDARIES)


def render_fragments(enrolled: dict, bindings: dict) -> list[tuple[str, str]]:
    """Render all fragments with a strict cap and nonempty boundary ranges."""
    proofs = {**enrolled, **bindings}
    if len(proofs) != len(enrolled) + len(bindings):
        raise fail("readiness enrollment and helper bindings overlap")
    if sorted(FRAGMENT_BOUNDARIES) != list(FRAGMENT_BOUNDARIES):
        raise fail("readiness fragment boundaries must be sorted")
    if any(boundary not in proofs for boundary in FRAGMENT_BOUNDARIES):
        missing = sorted(set(FRAGMENT_BOUNDARIES) - set(proofs))
        raise fail(
            f"readiness fragment boundary missing: {missing}; "
            "update FRAGMENT_BOUNDARIES"
        )
    rows: list[list[str]] = [[] for _ in FRAGMENT_NAMES]
    for path in sorted(proofs):
        reason = proofs[path]["reason"]
        rows[fragment_index(path)].append(
            f"  - file: {path}\n"
            "    tag: ~\n"
            "    class: postgres_ci\n"
            f'    reason: "{reason}"\n'
            "    runner: live-postgres-readiness\n"
        )
    outputs = []
    for index, rel in enumerate(fragment_paths()):
        if not rows[index]:
            raise fail(
                f"empty readiness fragment {rel}; update FRAGMENT_BOUNDARIES"
            )
        content = (
            "tests:\n" + "".join(rows[index])
            + "# Generated by scripts/generate-live-postgres-readiness.py; "
            "do not hand-edit.\n"
        )
        lines = len(content.splitlines())
        if lines > MAX_FRAGMENT_LINES:
            raise fail(
                f"generated {rel} has {lines} lines, over the "
                f"{MAX_FRAGMENT_LINES}-line budget; add a lexical boundary "
                "to FRAGMENT_BOUNDARIES and regenerate"
            )
        outputs.append((rel, content))
    return outputs


GENEREF_COMMENT = ("# Readiness enrollment is derived; do not hand-edit "
                   "this entry.")
SUITE = "live-postgres-readiness"
GRAPH_EXTRAS = (
    "ESHU_GRAPH_BACKEND",
    "ESHU_NEO4J_DATABASE",
    "ESHU_NEO4J_PASSWORD",
    "ESHU_NEO4J_URI",
    "ESHU_NEO4J_USERNAME",
)
DSN_VALUE = ("postgres://postgres:local-proof-only@127.0.0.1:15432"
             "/postgres?sslmode=disable")
READER_VALUE = ("postgres://postgres:local-proof-only@127.0.0.1:15433"
                "/postgres?sslmode=disable")
MAX_GENERATED_LINES = 500
# Lines reserved below the cap per shard so later enrollments grow a shard
# instead of tripping the budget on every addition.
SHARD_HEADROOM_LINES = 20
# Committed per-package name boundaries (#9149). A file's shard depends only
# on its own base name and this table, never on sibling sizes: the shard
# index is the count of boundaries the base name sorts at or after
# (LC_ALL=C order), so enrolling one file changes exactly one generated
# module. A shard that would pass the budget fails closed naming the
# boundary to add here.
SHARD_BOUNDARIES: dict[str, list[str]] = {
    "./internal/storage/postgres": ["m"],
}
WORKFLOW_BEGIN = ("# BEGIN GENERATED READINESS ENV "
                  "(scripts/generate-live-postgres-readiness.py; "
                  "do not hand-edit)")
WORKFLOW_END = "# END GENERATED READINESS ENV"


def render_pkg_module(package: str, files: dict) -> str:
    """Render one per-package inventory table."""
    lines = [
        "#!/usr/bin/env python3",
        f'"""Readiness enrollment for {package} (generated, data only).',
        "",
        "Do not edit by hand; regenerate with",
        "`python3 scripts/generate-live-postgres-readiness.py`.",
        '"""',
        "",
        "TABLE = {",
        f'    "{package}": {{',
    ]
    for rel in sorted(files):
        lines.append(f'        "{rel}": (')
        for name in files[rel]:
            lines.append(f'            "{name}",')
        lines.append("        ),")
    lines += ["    },", "}", ""]
    return "\n".join(lines)


def render_assembler(modules: list[str]) -> str:
    """Render the PACKAGES assembler over the per-package tables.

    Tables deep-merge per package: shards of one package combine instead
    of overwriting each other under their shared package key, which a
    shallow {**a, **b} merge would let the last shard win.
    """
    lines = [
        "#!/usr/bin/env python3",
        '"""Assembled PACKAGES for live-postgres-readiness (generated).',
        "",
        "Do not edit by hand; regenerate with",
        "`python3 scripts/generate-live-postgres-readiness.py`.",
        '"""',
        "",
    ]
    for index, module in enumerate(modules):
        lines.append(f"from {module} import TABLE as _TABLE_{index:02d}")
    lines += ["", "", "PACKAGES = {}", "for _table in ("]
    for index in range(len(modules)):
        lines.append(f"    _TABLE_{index:02d},")
    lines += [
        "):",
        "    for _package, _files in _table.items():",
        "        PACKAGES.setdefault(_package, {}).update(_files)",
        "",
    ]
    return "\n".join(lines)


def render_helpers(bindings: dict) -> str:
    """Render the helper pin table with freshly computed digests."""
    lines = [
        "#!/usr/bin/env python3",
        '"""Closed source dependencies exercised by enrolled readiness tests.',
        "",
        "These are Go files with no Test root of their own. Whole-file hashes",
        "bind the reviewed helper and consumer calls to the runtime proof.",
        "A source edit needs renewed review and proof before either pin",
        "changes. Generated; do not edit by hand.",
        '"""',
        "",
        "HELPER_PROOFS = {",
    ]
    for path, binding in sorted(bindings.items()):
        lines.append(f'    "{path}": {{')
        consumers = binding["consumers"]
        if len(consumers) == 1:
            # Preserve the reviewed four-field singleton record.
            consumer = consumers[0]
            for field in ("consumer_file", "consumer_test"):
                lines.append(f'        "{field}": "{consumer[field]}",')
            lines.append(f'        "helper_sha256": "{binding["helper_sha256"]}",')
            lines.append(f'        "consumer_sha256": "{consumer["consumer_sha256"]}",')
        else:
            lines.append(f'        "helper_sha256": "{binding["helper_sha256"]}",')
            lines.append('        "consumers": [')
            for consumer in consumers:
                lines.append("            {")
                for field in ("consumer_file", "consumer_test", "consumer_sha256"):
                    lines.append(f'                "{field}": "{consumer[field]}",')
                lines.append("            },")
            lines.append("        ],")
        lines.append("    },")
    return "\n".join(lines + ["}", ""])


def render_env_sh(required: list[str], optional: list[str]) -> str:
    """Render the sourced env-list data file for the runner and mirror."""
    lines = [
        "# Generated by scripts/generate-live-postgres-readiness.py;",
        "# do not hand-edit. Enrollment markers in the test files own",
        "# these lists; the runner and its mirror source this file.",
        "READINESS_DSN_VARS=(",
    ]
    lines += [f"  {var}" for var in sorted(
        var for var in required if var.endswith("_DSN"))]
    lines += [")", "READINESS_DISPOSABLE_VARS=("]
    lines += [f"  {var}" for var in sorted(
        var for var in required if var.endswith("_DISPOSABLE"))]
    lines += [")", "READINESS_OPT_IN_VARS=("]
    lines += [f"  {var}" for var in sorted(
        var for var in required if var == "ESHU_IAC_INVENTORY_LIVE")]
    lines += [")", "READINESS_OPTIONAL_WORKFLOW_VARS=("]
    lines += [f"  {var}" for var in optional]
    lines += [")", ""]
    return "\n".join(lines)


def workflow_value(var: str) -> str:
    """Map an env var to its workflow step value, failing closed."""
    if var == "ESHU_GRAPH_BACKEND":
        return "neo4j"
    if var == "ESHU_IAC_INVENTORY_LIVE":
        return "'1'"
    if var == "ESHU_NEO4J_URI":
        return "neo4j://127.0.0.1:7687"
    if var == "ESHU_NEO4J_USERNAME":
        return "neo4j"
    if var == "ESHU_NEO4J_PASSWORD":
        return "local-proof-only"
    if var == "ESHU_NEO4J_DATABASE":
        return "neo4j"
    if var.endswith("_READ_DSN"):
        return READER_VALUE
    if var.endswith("_DSN"):
        return DSN_VALUE
    if var.endswith("_DISPOSABLE"):
        return "'1'"
    raise fail(f"no workflow value rule for {var}")


def render_workflow_block(required: list[str], optional: list[str],
                          enrolled: dict) -> list[str]:
    """Render the workflow step env entries, LC_ALL=C sorted."""
    names = sorted(set(required) | set(optional))
    if any(rel.endswith("_graph_live_test.go") for rel in enrolled):
        names = sorted(set(names) | set(GRAPH_EXTRAS))
    return [f"          {var}: {workflow_value(var)}" for var in names]


def mutate_fragments_block(v1: str) -> str:
    """Ensure the fragments block carries exactly the generated entries."""
    head, sep, tail = v1.partition("\nfragments:\n")
    if not sep:
        raise fail("specs/live-tests.v1.yaml has no fragments block")
    kept = []
    for line in tail.splitlines(keepends=True):
        if (re.fullmatch(r"  - live-tests\.d/live-tests-readiness(?:-part[0-9]+)?\.generated\.yaml\n", line)
                or line.rstrip("\n") == f"  {GENEREF_COMMENT}"):
            continue
        if (re_fullmatch_ref(line) or line.strip() == ""
                or line.lstrip().startswith("#")):
            kept.append(line)
        else:
            raise fail(f"unexpected fragments block line: {line}")
    while kept and kept[-1].strip() == "":
        kept.pop()
    refs = "".join(f"  - {path.removeprefix('specs/')}\n"
                   for path in fragment_paths())
    return (head + "\nfragments:\n" + "".join(kept)
            + f"  {GENEREF_COMMENT}\n" + refs)


FRAGMENT_LINE = re.compile(r"  - live-tests\.d/[A-Za-z0-9._-]+\.yaml\n\Z")


def re_fullmatch_ref(line: str) -> bool:
    """Match a fragments entry line (same shape the registry accepts)."""
    return FRAGMENT_LINE.fullmatch(line) is not None


def mutate_workflow(text: str, interior: list[str]) -> str:
    """Replace the marked workflow env block interior."""
    numbered = list(enumerate(text.splitlines(keepends=True)))
    begin = next((i for i, line in numbered if WORKFLOW_BEGIN in line), None)
    end = next((i for i, line in numbered if WORKFLOW_END in line), None)
    if begin is None or end is None or end <= begin:
        raise fail("workflow generated env markers missing or unordered")
    lines = text.splitlines(keepends=True)
    interior_lines = [line + "\n" for line in interior]
    return "".join(lines[:begin + 1] + interior_lines + lines[end:])


def check_line_cap(rel: str, content: str) -> None:
    """Refuse to emit a generated file over the 500-line cap."""
    count = len(content.splitlines())
    if count > MAX_GENERATED_LINES:
        raise fail(f"generated {rel} has {count} lines; split it first")


def shard_index(package: str, basename: str) -> int:
    """Return the shard index for one file name under its package boundary.

    The index is the count of committed boundaries the base name sorts at
    or after, so it depends only on the file's own name and the table.
    """
    index = 0
    for bound in SHARD_BOUNDARIES.get(package, []):
        if basename >= bound:
            index += 1
        else:
            break
    return index


def shard_package(module: str, package: str, files: dict,
                    taken: set[str]) -> list[tuple[str, dict]]:
    """Split a package into _partN shards by its committed name boundary.

    Files stay in LC_ALL=C order inside each shard; shard names are fixed
    per index so later enrollments land in exactly one shard instead of
    reshuffling. A package with no boundary entry renders as one module
    byte-identical to render_pkg_module, and fails closed when that module
    would pass the budget. Shard names that collide with a real package
    module fail closed like package slug collisions.
    """
    bounds = SHARD_BOUNDARIES.get(package, [])
    if sorted(bounds) != bounds or len(set(bounds)) != len(bounds):
        raise fail(f"shard boundaries for {package} must be sorted unique: "
                   f"{bounds}")
    if any(not bound for bound in bounds):
        raise fail(f"shard boundaries for {package} must be non-empty: "
                   f"{bounds}")
    if not bounds:
        return [(module, files)]
    shards: dict[int, dict] = {}
    for rel in sorted(files):
        basename = rel.rsplit("/", 1)[-1]
        shards.setdefault(shard_index(package, basename), {})[rel] = (
            files[rel])
    out = []
    for index in sorted(shards):
        name = f"{module}_part{index + 1}"
        if name in taken:
            raise fail(f"module shard collision: {name}")
        taken.add(name)
        out.append((name, shards[index]))
    return out


def generated_outputs(root: pathlib.Path, enrolled: dict, bindings: dict,
                      required: list[str], optional: list[str]
                      ) -> list[tuple[str, str]]:
    """Compute every full-file generated output."""
    outputs: list[tuple[str, str]] = []
    outputs.extend(render_fragments(enrolled, bindings))
    modules = []
    packages = packages_of(enrolled)
    stale = sorted(set(SHARD_BOUNDARIES) - set(packages))
    if stale:
        raise fail(f"shard boundaries name unenrolled packages: {stale}; "
                   f"drop them from SHARD_BOUNDARIES")
    taken = {f"live_postgres_readiness_inventory_gen_{slug(p)}"
             for p in packages}
    limit = MAX_GENERATED_LINES - SHARD_HEADROOM_LINES
    for package in sorted(packages):
        module = f"live_postgres_readiness_inventory_gen_{slug(package)}"
        for shard, subset in shard_package(module, package,
                                           packages[package], taken):
            content = render_pkg_module(package, subset)
            lines = len(content.splitlines())
            if lines > limit:
                raise fail(
                    f"generated {shard} for {package} has {lines} lines, "
                    f"over the {limit}-line shard budget; add a name "
                    f"boundary to SHARD_BOUNDARIES[{package!r}] (now: "
                    f"{SHARD_BOUNDARIES.get(package, [])}) and regenerate")
            modules.append(shard)
            outputs.append((f"scripts/lib/{shard}.py", content))
    outputs.append(("scripts/lib/live_postgres_readiness_inventory_generated.py",
                    render_assembler(modules)))
    outputs.append(("scripts/lib/live_postgres_readiness_inventory_helpers.py",
                    render_helpers(bindings)))
    outputs.append(("scripts/lib/live_postgres_readiness_env.sh",
                    render_env_sh(required, optional)))
    for rel, content in outputs:
        if rel.startswith("scripts/"):
            check_line_cap(rel, content)
    return outputs
